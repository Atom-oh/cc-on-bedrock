import type { InstallerEnv } from "@/lib/install-env";
import { LOCAL_CLAUDE_MODELS as M } from "@/lib/local-models";

// ADR-006 installer for Windows PCs — the PowerShell counterpart of /api/install.
// Public (no auth), run from PowerShell or cmd:
//
//   powershell -NoProfile -ExecutionPolicy Bypass -Command "irm https://<dashboard>/api/install/windows | iex"
//
// The script:
//   1. Drops cc-bedrock-local.ps1 into %USERPROFILE%\.local\lib\cc-bedrock and a .cmd
//      shim into %USERPROFILE%\.local\bin, which it adds to the user PATH (only the
//      shim is on PATH: PowerShell would otherwise pick the .ps1 and refuse it under
//      the default execution policy)
//   2. Writes %USERPROFILE%\.config\cc-bedrock\config (owner-only ACL) with the
//      Cognito values baked in here
//   3. Runs `cc-bedrock-local setup` (Claude Code CLI + Claude Desktop Code tab via
//      ~/.claude/settings.json, Codex CLI + Codex app via ~/.codex/config.toml), then
//      `login` once
//   4. Optionally runs `setup-desktop` (Claude Desktop Cowork/Chat on Bedrock)
//
// The PowerShell text below avoids backticks and "${" so it can live in this
// template literal unescaped. Interpolated values are single-quoted PS literals.

export function psQuote(v: string): string {
  return `'${v.replace(/'/g, "''")}'`;
}

export function windowsInstallerScript(env: InstallerEnv): string {
  return `# cc-bedrock-local installer for Windows (ADR-006)
# Generated by ${env.dashboardUrl}/api/install/windows at ${new Date().toISOString()}
& {
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
try { [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12 } catch { }

$DashboardUrl = ${psQuote(env.dashboardUrl.replace(/\/+$/, ""))}
$CognitoRegion = ${psQuote(env.cognitoRegion)}
$CognitoUserPoolId = ${psQuote(env.cognitoUserPoolId)}
$CognitoClientId = ${psQuote(env.cognitoCliClientId)}
$CodexModel = ${psQuote(env.codexModelId)}

$LF = [string][char]10
$CRLF = [string][char]13 + [string][char]10
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$CfgDir = [IO.Path]::GetFullPath((Join-Path $env:USERPROFILE '.config/cc-bedrock'))
$CfgFile = Join-Path $CfgDir 'config'
$BinDir = [IO.Path]::GetFullPath((Join-Path $env:USERPROFILE '.local/bin'))
# The .ps1 lives outside PATH: PowerShell resolves a bare name to a .ps1 before a
# .cmd, and the default execution policy refuses to run it. PATH holds only the shim.
$LibDir = [IO.Path]::GetFullPath((Join-Path $env:USERPROFILE '.local/lib/cc-bedrock'))
$Cli = Join-Path $LibDir 'cc-bedrock-local.ps1'
$OldCli = Join-Path $BinDir 'cc-bedrock-local.ps1'
$Shim = Join-Path $BinDir 'cc-bedrock-local.cmd'

New-Item -ItemType Directory -Force -Path $CfgDir, $BinDir, $LibDir | Out-Null
# Owner-only: the directory will hold the Cognito refresh token and STS keys.
$Sid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
# Reset first (/inheritance:r alone keeps explicit ACEs added earlier), then fail
# closed before any token is written.
& icacls.exe $CfgDir /reset /T /C /Q | Out-Null
if ($LASTEXITCODE -eq 0) { & icacls.exe $CfgDir /inheritance:r /grant:r ('*' + $Sid + ':(OI)(CI)F') | Out-Null }
if ($LASTEXITCODE -ne 0) { throw ('could not restrict access to ' + $CfgDir + ' (icacls exit ' + $LASTEXITCODE + ')') }

Write-Host "[1/4] downloading cc-bedrock-local to $Cli"
Invoke-WebRequest -UseBasicParsing -Uri ($DashboardUrl + '/api/install/cli-ps1') -OutFile $Cli
Unblock-File -LiteralPath $Cli -ErrorAction SilentlyContinue
# An older install put the .ps1 in the PATH dir; it would shadow the shim.
if (Test-Path -LiteralPath $OldCli) { Remove-Item -LiteralPath $OldCli -Force }
$ShimText = '@echo off' + $CRLF + 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0../lib/cc-bedrock/cc-bedrock-local.ps1" %*' + $CRLF
[IO.File]::WriteAllText($Shim, $ShimText, [Text.Encoding]::ASCII)

Write-Host "[2/4] writing config to $CfgFile"
# Email is asked once and kept in config, so login only prompts the password.
$OldEmail = ''
if (Test-Path -LiteralPath $CfgFile) {
  $m = Select-String -LiteralPath $CfgFile -Pattern '^EMAIL=(.*)$' | Select-Object -First 1
  if ($m) { $OldEmail = $m.Matches[0].Groups[1].Value.Trim() }
}
$Prompt = '  Cognito email'
if ($OldEmail) { $Prompt = $Prompt + ' [' + $OldEmail + ']' }
$Email = Read-Host -Prompt $Prompt
if (-not $Email) { $Email = $OldEmail }
$Cfg = @(
  '# cc-bedrock-local config (owner-only). Edit as needed, or use:',
  '#   cc-bedrock-local set-model opus ${M.opus}',
  '#   cc-bedrock-local models',
  '',
  ('DASHBOARD_URL=' + $DashboardUrl),
  ('COGNITO_REGION=' + $CognitoRegion),
  ('COGNITO_USER_POOL_ID=' + $CognitoUserPoolId),
  ('COGNITO_CLIENT_ID=' + $CognitoClientId),
  ('EMAIL=' + $Email),
  'AWS_PROFILE_NAME=cc-bedrock',
  ('AWS_REGION=' + $CognitoRegion),
  '',
  '# Models (Bedrock inference profile IDs). ANTHROPIC_MODEL=opusplan backs /model',
  '# "Default": Opus for planning, Sonnet for execution.',
  'ANTHROPIC_MODEL=opusplan',
  'ANTHROPIC_DEFAULT_SONNET_MODEL=${M.sonnet}',
  'ANTHROPIC_DEFAULT_OPUS_MODEL=${M.opus}',
  'ANTHROPIC_DEFAULT_HAIKU_MODEL=${M.haiku}',
  'CLAUDE_CODE_SUBAGENT_MODEL=${M.subagent}',
  '',
  '# Codex (ADR-014): OpenAI on Bedrock. Must be a global./us. profile.',
  ('CODEX_MODEL=' + $CodexModel),
  '',
  '# Claude Desktop (setup-desktop): hosts Chat/Cowork may fetch. Unset = all (*).',
  '# Example: DESKTOP_EGRESS_HOSTS=docs.aws.amazon.com,*.github.com',
  '# DESKTOP_EGRESS_HOSTS=*   (none = block every fetch)'
)
[IO.File]::WriteAllText($CfgFile, (($Cfg -join $LF) + $LF), $Utf8NoBom)

Write-Host "[3/4] checking PATH"
$UserPath = [Environment]::GetEnvironmentVariable('Path', 'User')
if (-not $UserPath) { $UserPath = '' }
if (($UserPath -split ';') -contains $BinDir) {
  Write-Host "    $BinDir is already on PATH"
} else {
  [Environment]::SetEnvironmentVariable('Path', (($UserPath.TrimEnd(';') + ';' + $BinDir).TrimStart(';')), 'User')
  Write-Host "    added $BinDir to your user PATH (new terminals pick it up)"
}
if (-not (($env:Path -split ';') -contains $BinDir)) { $env:Path = $env:Path + ';' + $BinDir }

# Child process on the same console: prompts and output stay visible, and the
# CLI's exit codes cannot close this window.
function Invoke-Cli([string]$Sub) {
  $p = Start-Process -FilePath 'powershell.exe' -NoNewWindow -Wait -PassThru -ArgumentList @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ('"' + $Cli + '"'), $Sub)
  return $p.ExitCode
}

Write-Host ''
Write-Host "[4/4] point Claude Code and Codex at Bedrock? (Y/n)"
Write-Host '    writes ~/.claude/settings.json (Claude Code CLI + Claude Desktop Code tab) and'
Write-Host '    ~/.codex/config.toml (Codex CLI + Codex app); undo: cc-bedrock-local unsetup'
$Reply = Read-Host -Prompt '   '
if (-not $Reply) { $Reply = 'y' }
if ($Reply -match '^[Yy]') {
  # A failed setup (e.g. an invalid settings.json) leaves the tools unconfigured:
  # stop here rather than sign in and report Done. 'return' leaves this script
  # block only; 'exit' would close the user's PowerShell window under irm | iex.
  if ((Invoke-Cli setup) -ne 0) {
    Write-Host '  setup failed (see the message above) - fix it, then run: cc-bedrock-local setup; cc-bedrock-local login'
    return
  }
  Write-Host ''
  Write-Host 'Signing in once (a hidden task keeps the session renewed; you are asked again only when the 30-day sign-in ends):'
  if ((Invoke-Cli login) -ne 0) { Write-Host '  sign-in failed - retry with: cc-bedrock-local login' }

  Write-Host ''
  Write-Host 'Also switch Claude Desktop Cowork/Chat to Bedrock? (y/N)'
  Write-Host '    third-party mode: the app stops using claude.ai sign-in and uses your cc-bedrock role.'
  Write-Host '    Needs AWS CLI v2. Undo: cc-bedrock-local unsetup-desktop'
  $Desk = Read-Host -Prompt '   '
  if ($Desk -match '^[Yy]') { [void](Invoke-Cli setup-desktop) }
} else {
  Write-Host '  Skipped. Later: cc-bedrock-local setup; cc-bedrock-local login'
}

Write-Host ''
Write-Host 'Done. Restart Claude Desktop / the Codex app, then use them as usual:'
Write-Host '  claude                          # Claude Code on Bedrock (also the Claude Desktop Code tab)'
Write-Host '  codex                           # OpenAI Codex on Bedrock (also the Codex app)'
Write-Host '  cc-bedrock-local status         # session + limit state'
Write-Host '  cc-bedrock-local set-model opus=<id>'
Write-Host '  cc-bedrock-local login          # sign in again (or Start menu: cc-bedrock sign in)'
}
`;
}
